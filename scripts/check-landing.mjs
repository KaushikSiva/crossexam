import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.CROSSEXAM_SITE_URL||'http://127.0.0.1:5178/',{waitUntil:'networkidle'});
await page.waitForTimeout(1300);
await page.screenshot({path:'docs/assets/landing-hero.png'});
await page.locator('#evidence').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
assert.match(await page.locator('.evidence-output').innerText(),/8\/8/);
await page.getByRole('button',{name:'02 Does it generalize?'}).click().catch(()=>page.getByRole('button',{name:/Does it generalize/}).click());
assert.equal(await page.locator('.brief-audit>div').count(),8);
assert.match(await page.locator('.brief-audit').innerText(),/MISSED/);
await page.getByRole('button',{name:/Show me the failure/}).click();
assert.match(await page.locator('.brief-finding').innerText(),/atlas/);
assert.match(await page.locator('.brief-finding').innerText(),/beacon/);
await page.getByRole('button',{name:/View OpenUI program/}).click();
assert.match(await page.locator('.program-source').innerText(),/EvidencePanel/);
await page.getByRole('button',{name:/Hide OpenUI program/}).click();
await page.getByRole('button',{name:/Did it actually improve/}).click();
await page.waitForTimeout(300);
await page.screenshot({path:'docs/assets/landing-openui.png'});
await page.locator('#improvement').scrollIntoViewIfNeeded();
await page.locator('.version-selector button').last().click();
assert.match(await page.locator('.version-status').innerText(),/REJECTED/);
await page.waitForTimeout(1200);
await page.screenshot({path:'docs/assets/landing-learning.png'});
await page.getByRole('button',{name:/Watch the one-minute film/}).click();
await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
const duration=await page.locator('video').evaluate(v=>v.duration);
assert.ok(duration<=60&&duration>=50);
await page.keyboard.press('Escape');await page.waitForSelector('video',{state:'detached'});
await page.setViewportSize({width:390,height:844});
await page.goto(process.env.CROSSEXAM_SITE_URL||'http://127.0.0.1:5178/',{waitUntil:'networkidle'});
await page.waitForTimeout(1300);
await page.screenshot({path:'docs/assets/landing-mobile.png'});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
assert.deepEqual(errors,[]);
console.log('Landing verified: OpenUI rendering, all evidence views, rollback interaction, video playback, mobile layout, and no JS errors.');
await browser.close();
