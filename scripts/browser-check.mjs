import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

await fs.mkdir('docs/assets',{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.CROSSEXAM_URL||'http://127.0.0.1:8847/',{waitUntil:'networkidle'});
await page.waitForSelector('.case-button');
await page.waitForTimeout(2500);await page.screenshot({path:'docs/assets/workspace.png',fullPage:true});
assert.match(await page.locator('#case-detail').innerText(),/CONTRACT VIOLATED/);
assert.match(await page.locator('#case-detail').innerText(),/beacon/);
await page.locator('[data-case="1"]').click();
assert.match(await page.locator('#case-detail').innerText(),/Retries consume/);
await page.locator('.nav[data-view="learning"]').click();
await page.waitForTimeout(1200);
assert.equal(await page.locator('#version-table tbody tr').count(),5);
await page.waitForTimeout(2500);await page.screenshot({path:'docs/assets/learning.png',fullPage:true});
await page.locator('.nav[data-view="audit"]').click();
assert.equal(await page.locator('#audit-table tbody tr').count(),12);
await page.waitForTimeout(2500);await page.screenshot({path:'docs/assets/audit.png',fullPage:true});
await page.locator('.nav[data-view="evidence"]').click();
await page.waitForTimeout(2500);await page.screenshot({path:'docs/assets/evidence.png',fullPage:true});
const downloadPromise=page.waitForEvent('download');
await page.locator('#export').click();
const download=await downloadPromise;
assert.equal(download.suggestedFilename(),'crossexam-evidence.json');
await page.locator('#run').click();
await page.locator('#start-local').click();
await page.waitForFunction(()=>!document.querySelector('#progress').hidden);
await page.waitForFunction(()=>document.querySelector('#progress').hidden,{},{timeout:30000});
assert.equal(await page.locator('#notice').isVisible(),false);
await page.setViewportSize({width:390,height:844});
await page.locator('.nav[data-view="overview"]').click();
await page.waitForTimeout(2500);await page.screenshot({path:'docs/assets/mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Mobile has horizontal overflow');
assert.deepEqual(errors,[]);
console.log('Browser checks passed: views, evidence download, real campaign, mobile layout, no JS errors.');
await browser.close();
