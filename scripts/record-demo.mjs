import {chromium} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';

const config=JSON.parse(await fs.readFile('recordings/timing.json','utf8'));
await fs.mkdir('recordings/raw',{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1600,height:900},deviceScaleFactor:1,recordVideo:{dir:'recordings/raw',size:{width:1600,height:900}}});
const page=await context.newPage();
const banner=await fs.readFile('docs/assets/banner.svg','utf8');
const title=`<!doctype html><html><body style="margin:0;background:#171d19;display:flex;align-items:center;justify-content:center;height:100vh">${banner.replace('height="800"','height="800" style="width:100%;height:auto"')}</body></html>`;
await page.setContent(title);await page.waitForTimeout(config.durations[0]*1000);
await page.goto(process.env.CROSSEXAM_URL||'http://127.0.0.1:8847/',{waitUntil:'networkidle'});
await page.waitForSelector('.case-button');
await page.evaluate(()=>{document.body.classList.add('recording');const r=window.CrossExam.getReport();window.CrossExam.selectCase(r.counterexamples.findIndex(c=>c.id==='D01'));});
await page.waitForTimeout(config.durations[1]*1000);
await page.locator('.nav[data-view="learning"]').click();
await page.waitForTimeout(config.durations[2]*650);
await page.evaluate(()=>window.scrollTo({top:380,behavior:'smooth'}));
await page.waitForTimeout(config.durations[2]*350);
await page.locator('.nav[data-view="audit"]').click();
await page.waitForTimeout(config.durations[3]*1000);
await page.locator('.nav[data-view="evidence"]').click();
await page.waitForTimeout(config.durations[4]*1000);
await page.setContent(title);await page.waitForTimeout(config.durations[5]*1000);
const video=page.video();await context.close();
await video.saveAs('recordings/raw/crossexam-capture.webm');
await browser.close();
console.log('Recorded actual workspace to recordings/raw/crossexam-capture.webm');
